// Writes qml/pen.mjs: the web app's pen (app/web/public/ui.mjs, from "---- pen ----" up to "---- small drawings of
// the Desk ----": the drawings, the sketches, the session marks, the crown, the hand, the ring, the hues, a sub's card
// edge) for the Linux window, unchanged. The window draws the paths these functions write.
//   node app/linux/dev/pen.mjs          write it
//   node app/linux/dev/pen.mjs --check  exit 1 when qml/pen.mjs is not what ui.mjs gives (CI: linux.yml)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const ui = fs.readFileSync(path.join(here, '../../web/public/ui.mjs'), 'utf8')
const from = ui.indexOf('// ---- pen ----'), to = ui.indexOf('// ---- small drawings of the Desk ----')
if (from < 0 || to < from) throw new Error('ui.mjs: the pen section is not where it was (markers "---- pen ----", "---- small drawings of the Desk ----")')
const out = `// GENERATED by app/linux/dev/pen.mjs from app/web/public/ui.mjs: do not edit. The web app's pen, for the Linux window.
.pragma library
if (!Array.prototype.at) Array.prototype.at = function (i) { i = Math.trunc(i) || 0; return this[i < 0 ? this.length + i : i] }

${ui.slice(from, to).trimEnd()}

/** The d of every path in an svg string the pen wrote, its viewBox and its rotation: what the window draws. */
export function parts(svgText) {
  const box = /viewBox="([^"]+)"/.exec(svgText)?.[1].split(/\\s+/).map(Number) ?? [0, 0, 24, 24]
  const turn = Number(/rotate:(-?[\\d.]+)deg/.exec(svgText)?.[1] ?? 0)
  // (an exec loop: Qt's JavaScript has no matchAll)
  const paths = [], re = /<path([^>]*)\\sd="([^"]+)"([^>]*)>/g
  for (let m = re.exec(svgText); m; m = re.exec(svgText)) paths.push({ d: m[2], cls: /class="([^"]+)"/.exec(m[1] + m[3])?.[1] ?? '', width: Number(/stroke-width="([\\d.]+)"/.exec(m[1] + m[3])?.[1] ?? 0) })
  return { box, turn, paths }
}
`.replace('.pragma library\n', '')
const target = path.join(here, '../qml/pen.mjs')
if (process.argv.includes('--check')) {
  const have = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (have !== out) { console.error('app/linux/qml/pen.mjs is not what app/web/public/ui.mjs gives: node app/linux/dev/pen.mjs'); process.exit(1) }
  console.log('pen.mjs is current')
} else {
  fs.writeFileSync(target, out)
  console.log(`wrote ${path.relative(process.cwd(), target)}`)
}
